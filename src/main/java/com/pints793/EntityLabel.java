package com.pints793;

public class EntityLabel {

    private String id;
    private String name;

    public String getId() {
        return id;
    }

    public EntityLabel setId(String id) {
        this.id = id;
        return this;
    }

    public String getName() {
        return name;
    }

    public EntityLabel setName(String name) {
        this.name = name;
        return this;
    }
}
